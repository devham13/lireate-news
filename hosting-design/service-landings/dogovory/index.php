<section class="lx-section lx-reveal" id="faq">
  <span class="lx-section-label">FAQ</span>
  <h2>Вопросы о договорах в сфере ИС</h2>
  <details class="lx-faq"><summary>Нужно ли регистрировать лицензию в Роспатенте?</summary><p>Для ряда объектов (например, товарный знак) договор о распоряжении исключительным правом подлежит госрегистрации (ст. 1490, 1232 ГК РФ). Пошлина — п. 3.10 таблицы на rospatent.gov.ru.</p></details>
  <details class="lx-faq"><summary>Чем отличается лицензия от отчуждения?</summary><p>Лицензия сохраняет правообладателя и даёт право использования. Отчуждение переводит исключительное право другой стороне; регистрация — по п. 3.11.</p></details>
  <details class="lx-faq"><summary>Сколько стоит подготовка договора в LIREATE?</summary><p>Зависит от объекта и объёма. Рассчитаем за 15 минут после брифа — на сайте фиксированных цен нет.</p></details>
  <details class="lx-faq"><summary>Можно ли зарегистрировать договор авторского заказа?</summary><p>Авторское право возникает с создания произведения; отдельная регистрация договора в Роспатенте для текста или дизайна обычно не требуется. Регистрация нужна, если распоряжаетесь зарегистрированным объектом (ПО, знак).</p></details>
  <details class="lx-faq"><summary>Какие пошлины за регистрацию распоряжения?</summary><p>П. 3.10 и 3.11 приложения к ПП РФ № 941: 15 000 ₽ за первый объект и 13 000 ₽ за каждый дополнительный в одной заявлении. Сверяйте на https://rospatent.gov.ru/ru/activities/dues/table</p></details>
