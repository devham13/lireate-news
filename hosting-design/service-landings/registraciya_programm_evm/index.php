<section class="lx-section lx-reveal" id="faq">
  <span class="lx-section-label">FAQ</span>
  <h2>Вопросы о программах для ЭВМ и базах данных</h2>
  <details class="lx-faq"><summary>Обязательно ли регистрировать программу в Роспатенте?</summary><p>Нет. Исключительное право на программу возникает с момента создания (ст. 1262, 1259 ГК РФ). Регистрация добровольная, но даёт официальное свидетельство.</p></details>
  <details class="lx-faq"><summary>Сколько стоит госпошлина за регистрацию ПО?</summary><p>На странице госуслуги Роспатента указана пошлина 5 000 ₽ за регистрацию программы или БД. Точный пункт и сумму сверьте в таблице пошлин на rospatent.gov.ru на дату оплаты.</p></details>
  <details class="lx-faq"><summary>Можно ли в одной заявке зарегистрировать программу и базу данных?</summary><p>Нет. На каждую программу и каждую базу данных подаётся отдельная заявка.</p></details>
  <details class="lx-faq"><summary>Защищает ли регистрация ПО название приложения?</summary><p>Нет. Имя и иконку на витрине обычно охраняют товарным знаком. См. регистрацию товарного знака на LIREATE.</p></details>
  <details class="lx-faq"><summary>Что входит в защиту сайта?</summary><p>Договоры с разработчиками, регистрация кода, при необходимости знак и претензионная работа. Объём определяем после аудита.</p></details>
  <details class="lx-faq"><summary>Гарантируете ли регистрацию?</summary><p>Нет. Решение принимает Роспатент после проверки материалов.</p></details>
